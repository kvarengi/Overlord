#!/bin/bash

# Скрипт для запуска карты Веб3 Вселенной ДАО 23m00n

echo "🌙 Запуск карты Веб3 Вселенной ДАО 23m00n..."
echo "================================================"

# Проверяем, что мы в правильной директории
if [ ! -f "index.html" ]; then
    echo "❌ Ошибка: index.html не найден в текущей директории"
    echo "Убедитесь, что вы находитесь в папке проекта"
    exit 1
fi

# Останавливаем предыдущий сервер если он запущен
echo "🛑 Остановка предыдущего сервера..."
pkill -f "python3 -m http.server" 2>/dev/null || true

# Ждем немного
sleep 2

# Запускаем новый сервер
echo "🚀 Запуск HTTP сервера на порту 8000..."
echo "📱 Откройте браузер и перейдите по адресу:"
echo "   http://localhost:8000"
echo ""
echo "🌐 Или для доступа с других устройств:"
echo "   http://$(hostname -I | awk '{print $1}'):8000"
echo ""
echo "⏹️  Для остановки сервера нажмите Ctrl+C"
echo "================================================"

# Запускаем сервер
python3 -m http.server 8000 --bind 0.0.0.0